/**
 * Writes registry/check/mantis-check.mjs, the self-check an app built on Mantis runs: one file
 * with no dependencies, published as the registry item `check` and installed to
 * scripts/mantis-check.mjs. Its rules are the ones in eslint.config.mjs that make sense outside
 * this repo; its data (color names and values, type sizes, radius, motion and blur steps, the
 * names of Mantis's own files) comes from the token source and registry.json, so the fixes it
 * suggests never drift from the system.
 *
 * Modelled on quill-ds's check (same flags, exit codes and report format), because the Quill CLI
 * runs both. scripts/mantis-check.test.mjs fails when the committed file is stale.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { basename, dirname, join } from 'node:path'

import { tokens } from '../tokens/mantis.tokens.mjs'
import { toHex } from './contrast.mjs'
import { resolveValue } from './token-model.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const CHECK_PATH = join(root, 'registry/check/mantis-check.mjs')
const TEMPLATE_PATH = join(root, 'scripts/check/mantis-check.template.mjs')
const THEME_PATH = join(root, 'registry/mantis-theme.css')
const REGISTRY_PATH = join(root, 'registry.json')

// Token values come in rem, seconds and pixels; the check talks in pixels and milliseconds.
const number = (value) => {
  const [, amount, unit = ''] = String(value).match(/^(-?[0-9.]+)([a-z%]*)$/) ?? []
  if (amount === undefined) throw new Error(`build-check: '${value}' is not a plain number with a unit`)
  return Math.round(Number(amount) * (unit === 'rem' ? 16 : unit === 's' ? 1000 : 1) * 1000) / 1000
}
const resolved = (t, group) => Object.fromEntries(Object.entries(group).map(([name, value]) => [name, number(resolveValue(t, value, t.modes[0]))]))

// Every color utility name with the opaque value it paints, read from the published theme so a
// `var()` chain ends where the browser's would. See-through and gradient roles have no single
// color to be "nearest" to, so they are left out of the hints (they are still valid names).
export function swatches(t = tokens, css = readFileSync(THEME_PATH, 'utf8')) {
  const vars = new Map([...css.matchAll(/^\s*(--[a-z0-9-]+):\s*([^;]+);/gm)].map((m) => [m[1], m[2].trim()]))
  const follow = (value, depth = 0) => {
    const ref = value.match(/^var\((--[a-z0-9-]+)\)$/)
    return ref && vars.has(ref[1]) && depth < 12 ? follow(vars.get(ref[1]), depth + 1) : value
  }
  const out = {}
  for (const name of Object.keys(t.shadcn)) {
    const value = follow(t.shadcn[name])
    if (!/^(#[0-9a-f]{3,8}|rgba?\(.*\))$/i.test(value)) continue
    let hex
    try { hex = toHex(value)?.toLowerCase() } catch { continue } // toHex refuses a see-through color
    if (/^#[0-9a-f]{6}$/.test(hex ?? '')) out[name] = hex
  }
  return out
}

export function checkData(t = tokens, registry = JSON.parse(readFileSync(REGISTRY_PATH, 'utf8'))) {
  return {
    version: t.meta.version,
    colors: Object.keys(t.shadcn),
    swatches: swatches(t),
    text: resolved(t, t.text),
    radius: resolved(t, t.radius),
    durations: resolved(t, t.motion.duration),
    blurs: Object.fromEntries(Object.entries(t.blur).map(([name, value]) => [name, number(value)])),
    // Mantis's own blocks hold the reference's measured pixel values; installed into an app they
    // are recognised by file name, so the app is not asked to fix code it did not write.
    shipped: [...new Set(registry.items.filter((item) => item.type === 'registry:block' || item.type === 'registry:component').flatMap((item) => item.files.map((file) => basename(file.path))))].sort(),
  }
}

export function renderCheck(data = checkData()) {
  return [
    '#!/usr/bin/env node',
    '// mantis-check — generated by the Mantis design system (scripts/build-check.mjs) from the token',
    '// source. Do not edit by hand: reinstall with',
    '//   npx shadcn@latest add @mantis/check --overwrite',
    '// Usage: node scripts/mantis-check.mjs [--dir <path>]… [--css <tailwind entry>] [--include-ui] [--json] [--quiet]',
    "import { readFileSync, readdirSync, statSync, existsSync, realpathSync } from 'node:fs'",
    "import { fileURLToPath } from 'node:url'",
    "import { join, relative, resolve, extname } from 'node:path'",
    '',
    `export const DATA = ${JSON.stringify(data, null, 1)}`,
    '',
    readFileSync(TEMPLATE_PATH, 'utf8'),
  ].join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(dirname(CHECK_PATH), { recursive: true })
  writeFileSync(CHECK_PATH, renderCheck())
  console.log(`wrote ${CHECK_PATH.slice(root.length + 1)}`)
}
